#!/usr/bin/env python3
"""Generate docs/trace.md from the `vector <name> covers <IDs>` lines of the conformance vectors."""
import re, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
cov = {}
for f in sorted((root / "tests/conformance/vec").rglob("*.vec")):
    for line in f.read_text().splitlines():
        m = re.match(r"vector (\S+) covers (.+)", line)
        if m:
            for rid in m.group(2).split():
                cov.setdefault(rid, []).append(m.group(1))
out = ["# Requirement trace (generated by tools/trace.py)", "",
       "A requirement is listed only if at least one conformance vector names it. Passing is shown by `make test`;",
       "this file does not claim anything the vectors do not exercise.", "",
       "| Requirement | Vectors |", "|---|---|"]
for rid in sorted(cov):
    out.append(f"| {rid} | {', '.join(cov[rid])} |")
(root / "docs/trace.md").write_text("\n".join(out) + "\n")
print(len(cov), "requirements traced")
